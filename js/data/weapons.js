      id: o.id,
      name: o.name,
      manufacturer: o.maker,
      family: o.family,
      caliber: o.caliber,
      tier: o.tier,
      unlockCost: o.cost,
      requiresRange: t.range,
      inspiration: o.insp,
      blurb: o.blurb,
      strength: o.strength,
      tradeoff: o.tradeoff,
